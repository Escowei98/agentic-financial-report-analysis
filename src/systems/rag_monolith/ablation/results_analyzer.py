"""
Results analysis and best_config.yaml generation for the ablation study.

Reads an Optuna study and:
  1. Finds the best trial configuration
  2. Exports it to configs/best_config.yaml
  3. Generates summary tables and visualizations
"""

import logging
from datetime import datetime
from pathlib import Path

import optuna
import yaml

logger = logging.getLogger(__name__)


def get_best_config(study: optuna.Study) -> dict:
    """
    Extract the best configuration from an Optuna study.

    Returns:
        Dict with best parameters and RAGAS scores.
    """
    best_trial = study.best_trial

    return {
        "params": best_trial.params,
        "scores": {
            "composite_score": best_trial.user_attrs.get("composite_score", best_trial.value),
            "context_precision": best_trial.user_attrs.get("context_precision", 0.0),
            "context_recall": best_trial.user_attrs.get("context_recall", 0.0),
            "faithfulness": best_trial.user_attrs.get("faithfulness", 0.0),
        },
        "metadata": {
            "trial_number": best_trial.number,
            "total_trials": len(study.trials),
            "avg_latency": best_trial.user_attrs.get("avg_latency", 0.0),
            "total_tokens": best_trial.user_attrs.get("total_tokens", 0),
        },
    }


def save_best_config(
    study: optuna.Study,
    output_path: str | Path = "configs/best_config.yaml",
) -> Path:
    """
    Save the best configuration to a YAML file.

    Args:
        study: Completed Optuna study.
        output_path: Path for the output YAML file.

    Returns:
        Path to the created file.
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    best = get_best_config(study)

    # Build YAML content
    config = {
        "_meta": {
            "generated": datetime.now().isoformat(),
            "study_name": study.study_name,
            "total_trials": best["metadata"]["total_trials"],
            "best_trial": best["metadata"]["trial_number"],
        },
        "chunk_size": best["params"]["chunk_size"],
        "bm25_weight": best["params"]["bm25_weight"],
        "pre_rerank_k": best["params"]["pre_rerank_top_k"],
        "post_rerank_k": best["params"]["post_rerank_top_k"],
        "overlap": best["params"]["overlap_pct"],
        "scores": best["scores"],
    }

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(
            "# Auto-generated by Optuna ablation study\n"
            f"# Date: {datetime.now().strftime('%Y-%m-%d')} | "
            f"Trials: {best['metadata']['total_trials']} | "
            f"Best Score: {best['scores']['composite_score']:.4f}\n\n"
        )
        yaml.dump(config, f, default_flow_style=False, sort_keys=False)

    logger.info("Best config saved to %s", output_path)
    return output_path


def generate_summary_table(study: optuna.Study) -> list[dict]:
    """
    Generate a summary table of all trials as list of dicts.

    Each dict contains the trial parameters, scores, and metadata.
    Can be converted to a pandas DataFrame for notebooks.

    Returns:
        List of dicts, one per trial.
    """
    rows = []
    for trial in study.trials:
        if trial.state != optuna.trial.TrialState.COMPLETE:
            continue

        row = {
            "trial": trial.number,
            **trial.params,
            "composite_score": trial.user_attrs.get("composite_score", trial.value),
            "context_precision": trial.user_attrs.get("context_precision", 0.0),
            "context_recall": trial.user_attrs.get("context_recall", 0.0),
            "faithfulness": trial.user_attrs.get("faithfulness", 0.0),
            "avg_latency": trial.user_attrs.get("avg_latency", 0.0),
            "total_tokens": trial.user_attrs.get("total_tokens", 0),
        }
        rows.append(row)

    # Sort by composite score descending
    rows.sort(key=lambda r: r["composite_score"], reverse=True)
    return rows


def print_top_trials(study: optuna.Study, n: int = 10) -> None:
    """Print the top-N trial configurations and scores."""
    rows = generate_summary_table(study)

    print(f"\n{'='*80}")
    print(f"  Top {min(n, len(rows))} Configurations (of {len(rows)} completed trials)")
    print(f"{'='*80}\n")

    header = (
        f"{'#':>3} | {'Chunk':>5} | {'Overlap':>7} | {'BM25':>5} | "
        f"{'Pre-K':>5} | {'Post-K':>6} | {'Composite':>9} | "
        f"{'Prec':>5} | {'Rec':>5} | {'Faith':>5}"
    )
    print(header)
    print("-" * len(header))

    for row in rows[:n]:
        print(
            f"{row['trial']:>3} | "
            f"{row.get('chunk_size', 'N/A'):>5} | "
            f"{row.get('overlap_pct', 0)*100:>6.0f}% | "
            f"{row.get('bm25_weight', 0):>5.1f} | "
            f"{row.get('pre_rerank_top_k', 0):>5} | "
            f"{row.get('post_rerank_top_k', 0):>6} | "
            f"{row['composite_score']:>9.4f} | "
            f"{row['context_precision']:>5.3f} | "
            f"{row['context_recall']:>5.3f} | "
            f"{row['faithfulness']:>5.3f}"
        )
    print()
